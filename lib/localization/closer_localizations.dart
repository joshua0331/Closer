String tr(String english) {
  final language = CloserLocaleController.locale.value.languageCode;
  return _translations[language]?[english] ?? english;
}

String trParams(String english, Map<String, String> values) {
  var translated = tr(english);
  for (final entry in values.entries) {
    translated = translated.replaceAll('{${entry.key}}', entry.value);
  }
  return translated;
}
