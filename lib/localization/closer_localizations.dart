import 'package:flutter/material.dart';
import 'package:shared_preferences/shared_preferences.dart';

class CloserLocaleController {
  CloserLocaleController._();

  static const preferenceKey = 'closer_ui_language';
  static const supportedLocales = <Locale>[
    Locale('en'),
    Locale('id'),
    Locale('ms'),
    Locale('hi'),
    Locale('fil'),
  ];
  static final ValueNotifier<Locale> locale = ValueNotifier<Locale>(
    const Locale('en'),
  );

  static String normalize(String? code) =>
      supportedLocales.any((locale) => locale.languageCode == code)
      ? code!
      : 'en';

  static Future<void> load(SharedPreferences preferences) async {
    setLanguage(preferences.getString(preferenceKey));
  }

  static void setLanguage(String? code) {
    final next = Locale(normalize(code));
    if (locale.value != next) locale.value = next;
  }

  static Future<void> saveLanguage(
    SharedPreferences preferences,
    String code,
  ) async {
    final normalized = normalize(code);
    if (preferences.getString(preferenceKey) != normalized) {
      await preferences.setString(preferenceKey, normalized);
    }
    setLanguage(normalized);
  }
}

